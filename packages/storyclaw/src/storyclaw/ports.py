"""Per-run adapters supplied by the host, never mutable process-global user state."""
from typing import Protocol
from .contracts import CapabilityResult, ModelTurn

class StoryPorts(Protocol):
    async def execute(self, name: str, arguments: dict) -> CapabilityResult: ...
    async def model_turn(self, messages: list[dict], tools: list[dict]) -> ModelTurn: ...
    async def emit(self, event: str, payload: dict) -> None: ...

    async def lifecycle(self, action: str, run_id: str, data: dict | None = None) -> dict | list: ...
